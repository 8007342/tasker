// Writes <dir>/sw.js: a service worker that precaches exactly what the build produced.
// Its version comes from the files' hashes, so any change to the build ships an update.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "build/web";
// Standalone pages, by file and by the address that serves them. Cloudflare redirects the
// ".html" form, so the clean address is what gets cached.
const PAGES = { "qr.html": "qr" };
const skip = (name) =>
  name in PAGES || ["sw.js", "index.html", ".last_build_id", "flutter_service_worker.js", "version.json", "_headers"].includes(name) ||
  name.endsWith(".map") || name.includes("skwasm");

const files = readdirSync(dir, { recursive: true, withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => join(entry.parentPath, entry.name).slice(dir.length + 1))
  .filter((name) => !skip(name))
  .sort();

const hash = createHash("sha256");
for (const name of [...files, "index.html", ...Object.keys(PAGES)]) hash.update(name).update(readFileSync(join(dir, name)));
const version = hash.digest("hex").slice(0, 16);

// "./" and not "index.html": Cloudflare redirects the latter, and a redirected response
// cannot answer a navigation.
const urls = ["./", ...Object.values(PAGES), ...files.map((name) => name.split("/").map(encodeURIComponent).join("/"))];

writeFileSync(join(dir, "sw.js"), `// Generated by tool/gen_sw.mjs. Do not edit.
const CACHE = "tasker-${version}";
const FILES = ${JSON.stringify(urls)};
const PAGES = new Set(${JSON.stringify(Object.values(PAGES).map((page) => "/" + page))});

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(FILES.map((url) => new Request(url, { cache: "reload" })));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== location.origin || url.pathname.startsWith("/api/")) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = request.mode === "navigate"
      ? await cache.match(PAGES.has(url.pathname) ? url.pathname.slice(1) : "./")
      : await cache.match(request, { ignoreSearch: true });
    return cached ?? fetch(request);
  })());
});
`);
console.log(`sw.js: ${urls.length} files, version ${version}`);
